// Convert markdown bold (**text**) to HTML strong or JSX formatted structure
export const markdownToHtml = (text) => {
  if (!text) return '';
  return text
    .replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')
    .replace(/\n\n+/g, '</p><p>')
    .replace(/\n/g, '<br/>');
};
