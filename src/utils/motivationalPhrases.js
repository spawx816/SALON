const STORAGE_KEY = 'pb_reception_phrase_state';
const ROTATION_INTERVAL_MS = 30 * 60 * 1000; // 30 minutos

// Algoritmo de barajado Fisher-Yates para rotación no repetitiva
const generateShuffledIndices = (length) => {
  const arr = Array.from({ length }, (_, i) => i);
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
};

const getStoredState = () => {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return null;
    return JSON.parse(raw);
  } catch (e) {
    return null;
  }
};

const saveState = (state) => {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
  } catch (e) {}
};

/**
 * Obtiene la frase actual según la rotación de 30 minutos sin repetir
 */
export const getCurrentMotivationalPhrase = () => {
  const now = Date.now();
  let state = getStoredState();

  // Si no hay estado o el orden está corrupto/incompleto, inicializar ciclo completo
  if (!state || !Array.isArray(state.order) || state.order.length !== RECEPTION_PHRASES.length) {
    state = {
      order: generateShuffledIndices(RECEPTION_PHRASES.length),
      currentIndex: 0,
      lastRotatedAt: now
    };
    saveState(state);
  }

  // Verificar si han pasado 30 minutos desde la última rotación
  const elapsed = now - (state.lastRotatedAt || 0);
  if (elapsed >= ROTATION_INTERVAL_MS) {
    const stepsToAdvance = Math.floor(elapsed / ROTATION_INTERVAL_MS);
    let nextIndex = state.currentIndex + stepsToAdvance;
    let newOrder = [...state.order];

    // Si completó la lista entera, reiniciar barajado completo sin repetir
    if (nextIndex >= newOrder.length) {
      newOrder = generateShuffledIndices(RECEPTION_PHRASES.length);
      nextIndex = nextIndex % newOrder.length;
    }

    state = {
      order: newOrder,
      currentIndex: nextIndex,
      lastRotatedAt: now - (elapsed % ROTATION_INTERVAL_MS)
    };
    saveState(state);
  }

  const phraseIndex = state.order[state.currentIndex] ?? 0;
  return {
    ...RECEPTION_PHRASES[phraseIndex],
    orderPosition: state.currentIndex + 1,
    totalPhrases: RECEPTION_PHRASES.length,
    nextRotationInMs: Math.max(0, ROTATION_INTERVAL_MS - (now - state.lastRotatedAt))
  };
};

/**
 * Fuerza el avance a la siguiente frase sin repetir
 */
export const advanceToNextPhrase = () => {
  const now = Date.now();
  let state = getStoredState();

  if (!state || !Array.isArray(state.order) || state.order.length !== RECEPTION_PHRASES.length) {
    state = {
      order: generateShuffledIndices(RECEPTION_PHRASES.length),
      currentIndex: 0,
      lastRotatedAt: now
    };
  }

  let nextIndex = state.currentIndex + 1;
  let newOrder = [...state.order];

  if (nextIndex >= newOrder.length) {
    newOrder = generateShuffledIndices(RECEPTION_PHRASES.length);
    nextIndex = 0;
  }

  state = {
    order: newOrder,
    currentIndex: nextIndex,
    lastRotatedAt: now
  };
  saveState(state);

  const phraseIndex = state.order[state.currentIndex] ?? 0;
  return {
    ...RECEPTION_PHRASES[phraseIndex],
    orderPosition: state.currentIndex + 1,
    totalPhrases: RECEPTION_PHRASES.length,
    nextRotationInMs: ROTATION_INTERVAL_MS
  };
};
